function chordIntervals(block: ChordBlock): number[] {
  const result = [...QUALITY_INTERVALS[block.quality]];
  for (const extension of block.extensions) {
    const interval = EXTENSION_INTERVALS[extension.toLowerCase()];
    if (interval !== undefined) result.push(interval);
  }
  return [...new Set(result)];
}

/** Stage 1: parse harmony into a beat-resolution pitch-class timeline. */
export class HarmonicParser {
  parse(config: ProjectConfig, blocks: ChordBlock[]): ParsedHarmony[] {
    const scale = new Set(MODE_INTERVALS[normalizeMode(config.scaleMode)].map((interval) => pc(config.keyRoot + interval)));
    const beatTicks = (PPQ * 4) / config.timeSignature[1];
    const sorted = blocks.map((block) => ({ ...block, rootPitchClass: pc(block.rootPitchClass) })).sort((a, b) => a.startTime - b.startTime);
    const result: ParsedHarmony[] = [];
    sorted.forEach((block, chordIndex) => {
      let root = block.rootPitchClass;
      let bass = block.bassOverride === undefined ? root : pc(block.bassOverride);
      let intervals = chordIntervals(block);
      if (block.symbol) {
        const parsed = parseChord(block.symbol);
        if (parsed.ok) {
          root = parsed.chord.root;
          bass = block.bassOverride === undefined ? (parsed.chord.bass ?? root) : pc(block.bassOverride);
          intervals = parsed.chord.pitchClasses.map((tone) => pc(tone - root));
        }
      }
      const pitchClasses = uniq(intervals.map((interval) => root + interval)).sort((a, b) => a - b);
      const third = pitchClasses.find((tone) => [3, 4, 5].includes(pc(tone - root)));
      const seventh = pitchClasses.find((tone) => [9, 10, 11].includes(pc(tone - root)));
      const guideTones = [third, seventh].filter((tone): tone is number => tone !== undefined);
      const colorTones = pitchClasses.filter((tone) => ![root, ...guideTones, pc(root + 7)].includes(tone));
      const duration = Math.max(1, block.duration);
      const tension = clamp(0.12 + colorTones.length * 0.08 + pitchClasses.filter((tone) => !scale.has(tone)).length * 0.04, 0, 0.7);
      for (let time = block.startTime; time < block.startTime + duration; time += beatTicks) {
        result.push({ startTime: time, duration: Math.min(beatTicks, block.startTime + duration - time), chordIndex,
          rootPitchClass: root, bassPitchClass: bass, pitchClasses, guideTones, colorTones, commonTones: [], tension });
      }
    });
    for (let i = 1; i < result.length; i++) {
      if (result[i - 1].chordIndex !== result[i].chordIndex) {
        const prior = new Set(result[i - 1].pitchClasses);
        result[i].commonTones = result[i].pitchClasses.filter((tone) => prior.has(tone));
      }
    }
    return result;
  }
}

/** Stage 2: map the sectional baseline/override and harmonic tension to a continuous macro curve. */
export class DynamicMappingEngine {
  map(timeline: ParsedHarmony[], sections: StructureSection[], config: ProjectConfig, profiles: InstrumentProfile[]): EnergyPoint[] {
    if (!timeline.length) return [];
    const beatTicks = (PPQ * 4) / config.timeSignature[1];
    const end = Math.max(...timeline.map((item) => item.startTime + item.duration));
    const sortedSections = [...sections].sort((a, b) => a.startTime - b.startTime);
    const groupFor = (section: SectionType, energy: number): string[] => {
      if (section === "Chorus" || energy >= 0.82) return ["strings", "brass", "woodwinds", "percussion", "keys"];
      if (section === "Intro" || section === "Verse" || section === "Breakdown") return ["strings", "woodwinds", "keys"];
      return ["strings", "brass", "woodwinds", "keys"];
    };
    const points: EnergyPoint[] = [];
    for (let time = timeline[0].startTime; time < end; time += beatTicks) {
      const harmony = timeline.find((item) => item.startTime <= time && time < item.startTime + item.duration) ?? timeline[timeline.length - 1];
      const section = sortedSections.find((item) => item.startTime <= time && time < item.startTime + item.duration);
      const sectionType = section?.type ?? "Verse";
      const baseline = BASE_DYNAMICS[sectionType];
      const override = section ? clamp(section.targetDynamic, 0, 1) : baseline;
      const energy = clamp(override * 0.86 + baseline * 0.08 + harmony.tension * 0.06, 0, 1);
      const densityName = section?.densityLevel ?? (energy >= 0.82 ? "Tutti" : energy >= 0.55 ? "Balanced" : "Sparse");
      const densityGroups = densityName === "Tutti" ? ["strings", "brass", "woodwinds", "percussion", "keys"] : densityName === "Dense" ? ["strings", "brass", "woodwinds", "keys"] : densityName === "Sparse" ? ["strings", "woodwinds", "keys"] : groupFor(sectionType, energy);
      const activeGroups = densityGroups.filter((group) => profiles.some((profile) => profile.family === group));
      points.push({ time, duration: Math.min(beatTicks, end - time), value: energy, sectionType,
        density: clamp(DENSITY_VALUES[densityName], 0, 1), activeGroups, tension: harmony.tension });
    }
    return points;
  }
}

/** Stage 3: map the preset style and active energy to five named orchestral texture functions. */
export class TextureRoleAllocator {
  allocate(config: ProjectConfig, energies: EnergyPoint[], profiles: InstrumentProfile[], variation?: () => number): TextureLayer[] {
    const style = config.presetStyle.toLowerCase();
    const candidates: Record<SemanticRole, string[]> = style.includes("chamber")
      ? { LEAD: ["oboes", "violins1", "flutes"], COUNTERLINE: ["violins2", "clarinets"], PAD: ["violas", "horns"], OSTINATO: ["piano", "harp"], BASS: ["cellos", "bassoons"] }
      : style.includes("cinematic")
        ? { LEAD: ["violins1", "flutes", "oboes"], COUNTERLINE: ["horns", "violins2", "clarinets"], PAD: ["violas", "horns", "piano"], OSTINATO: ["harp", "piano"], BASS: ["cellos", "tuba", "bassoons"] }
        : { LEAD: ["violins1", "oboes", "flutes"], COUNTERLINE: ["violins2", "clarinets", "oboes"], PAD: ["violas", "horns", "piano"], OSTINATO: ["harp", "piano"], BASS: ["cellos", "bassoons", "tuba"] };
    const definitions: Array<{ role: SemanticRole; range: { low: number; high: number }; articulation: SemanticArticulation }> = [
      { role: "BASS", range: { low: 28, high: 48 }, articulation: "LEGATO" },
      { role: "OSTINATO", range: { low: 43, high: 64 }, articulation: "SPICCATO" },
      { role: "PAD", range: { low: 55, high: 76 }, articulation: "LEGATO" },
      { role: "COUNTERLINE", range: { low: 62, high: 83 }, articulation: "DETACHE" },
      { role: "LEAD", range: { low: 69, high: 91 }, articulation: "LEGATO" },
    ];
    const activeGroups = new Set(energies.flatMap((point) => point.activeGroups));
    return definitions.map((definition) => {
      const optionsForRole = candidates[definition.role]
        .map((role) => profiles.find((profile) => profile.role === role && (!activeGroups.size || activeGroups.has(profile.family ?? ""))))
        .filter((profile): profile is InstrumentProfile => profile !== undefined);
      const fallback = profiles.find((profile) => !activeGroups.size || activeGroups.has(profile.family ?? "")) ?? profiles[0];
      const selected = optionsForRole[0] ?? fallback;
      const energyDensity = energies.reduce((sum, item) => sum + item.density, 0) / Math.max(1, energies.length);
      const roll = variation ? variation() : 0.5;
      const jittered = energyDensity + (roll - 0.5) * 0.3;
      const voices = definition.role === "BASS" || definition.role === "LEAD" ? 1
        : definition.role === "OSTINATO" ? 1 + Math.floor(jittered * 1.9)      // 1–2
        : definition.role === "PAD" ? clamp(Math.round(jittered * 3.2), 2, 4)  // 2–4
        : 1 + Math.floor(jittered * 2.1);                                      // COUNTERLINE 1–3
      const rotation = variation && optionsForRole.length ? Math.floor(variation() * optionsForRole.length) : 0;
      const assigned = optionsForRole.length ? Array.from({ length: voices }, (_, index) => optionsForRole[(index + rotation) % optionsForRole.length]!) : selected ? [selected] : [];
      const range = selected?.comfortableRange ?? selected?.writtenRange ?? definition.range;
      return { ...definition, instrumentIds: assigned.map((profile) => profile.id), range, density: clamp(energyDensity, 0.15, 1) };
    });
  }
}

function pitchInClass(pitchClass: number, range: { low: number; high: number }, preferred: number): number {
  const valid: number[] = [];
  for (let pitch = range.low; pitch <= range.high; pitch++) if (pc(pitch) === pc(pitchClass)) valid.push(pitch);
  if (!valid.length) return clamp(preferred, range.low, range.high);
  return valid.reduce((best, pitch) => Math.abs(pitch - preferred) < Math.abs(best - preferred) ? pitch : best, valid[0]);
}

/** Stage 4: realize ordered chord voicings and enforce consonant sub-C3 spacing. */
export class OvertoneSpacingFilter {
  apply(timeline: ParsedHarmony[], layers: TextureLayer[], energies: EnergyPoint[], algorithm: VoicingAlgorithm = "OVERTONE_SPREAD"): VoicedHarmony[] {
    const byRole = new Map(layers.map((layer) => [layer.role, layer]));
    const roles: SemanticRole[] = ["BASS", "OSTINATO", "PAD", "COUNTERLINE", "LEAD"];
    return timeline.map((harmony) => {
      const energy = energies.find((item) => item.time <= harmony.startTime && harmony.startTime < item.time + item.duration)?.value ?? 0.5;
      const pcs = harmony.pitchClasses;
      const tones = [harmony.bassPitchClass, pcs.find((tone) => tone === pc(harmony.rootPitchClass + 7)) ?? pcs[0],
        harmony.guideTones[0] ?? pcs[0], harmony.guideTones[1] ?? pcs[1] ?? pcs[0], pcs.find((tone) => ![harmony.rootPitchClass, ...harmony.guideTones].includes(tone)) ?? pcs[0]];
      const pitches: number[] = [];
      const voices: VoicedHarmony["voices"] = [];
      for (let index = 0; index < roles.length; index++) {
        const layer = byRole.get(roles[index])!;
        const minimum = index === 0 ? layer.range.low : pitches[index - 1] + (index < 2 ? 7 : 3);
        const preferred = [36, 52, 64, 74, 82][index];
        let pitch = pitchInClass(tones[index], { low: Math.max(layer.range.low, minimum), high: layer.range.high }, preferred);
        // Below C3 (MIDI 48), only octave-equivalent roots are permitted. The bass anchor is root-only.
        if (pitch < 48 && pc(pitch) !== harmony.bassPitchClass) {
          pitch = pitchInClass(harmony.bassPitchClass, { low: Math.max(24, layer.range.low), high: Math.min(47, layer.range.high) }, 36);
        }
        if (index > 0 && pitch <= pitches[index - 1]) pitch = pitchInClass(tones[index], { low: pitches[index - 1] + 1, high: layer.range.high }, preferred);
        pitches.push(pitch);
        voices.push({ role: roles[index], instrumentId: layer.instrumentIds[0], pitch });
      }
      if (algorithm === "OPEN_SPREAD" || algorithm === "OVERTONE_SPREAD") {
        for (let index = 1; index < pitches.length; index++) if (pitches[index] - pitches[index - 1] < (index < 2 ? 7 : 3)) pitches[index] += 12;
      }
      const safe = pitches.map((pitch, index) => clamp(pitch, byRole.get(roles[index])!.range.low, byRole.get(roles[index])!.range.high));
      if (algorithm === "DROP_2" && safe.length >= 4) {
        const lowered = safe[3] - 12;
        if (lowered >= byRole.get(roles[3])!.range.low && lowered > safe[2]) safe[3] = lowered;
      } else if (algorithm === "SEMI_OPEN" && safe.length >= 4) {
        // Spec: drop the 2nd voice from the top an octave; covers DROP_2's geometry while
        // inner voices bridge the residual gap through the stage-4 spacing fixup below.
        const lowered = safe[3] - 12;
        if (lowered >= byRole.get(roles[3])!.range.low && lowered > safe[2]) safe[3] = lowered;
      } else if (algorithm === "CLOSED") {
        for (let index = 1; index < safe.length; index++) {
          if (safe[index] - safe[index - 1] > 12) safe[index] -= 12;
        }
      } else if (algorithm === "CLUSTER") {
        for (let index = 1; index < safe.length; index++) {
          const layer = byRole.get(roles[index])!;
          const tone = tones[index];
          const candidates = Array.from({ length: layer.range.high - layer.range.low + 1 }, (_, offset) => layer.range.low + offset)
            .filter((pitch) => pc(pitch) === tone && pitch >= safe[index - 1] + 1 && pitch <= safe[index - 1] + 3);
          if (candidates.length) safe[index] = candidates[0];
        }
      }
      for (let index = 1; index < safe.length; index++) {
        const low = byRole.get(roles[index])!.range.low;
        const high = byRole.get(roles[index])!.range.high;
        if (safe[index] <= safe[index - 1]) {
          const lifted = safe[index] + 12 * Math.ceil((safe[index - 1] + 1 - safe[index]) / 12);
          safe[index] = lifted <= high ? lifted : clamp(safe[index - 1] + 1, low, high);
        }
      }
      return { ...harmony, pitches: safe, voices: voices.map((voice, index) => ({ ...voice, pitch: safe[index] })), energy };
    });
  }
}

/**
 * Stage 4.5: enforce the overtone-zone interval matrix between adjacent semantic
 * voices. Deterministic, NO randomness and NO new RNG salt (Module 5 is fully
 * deterministic by design). Pitch-class preserving: repairs by raising the UPPER
 * voice of a violating pair by octaves into compliance (never lowers, never
 * re-spells pitch class), cascading upward if a raise collides with the next
 * voice, then re-applying the existing monotonic ordering fix inside its window.
 * Spec calls this "reject candidates"; this architecture realizes exactly five
 * voices per slice, so rejection is implemented as repair + flag instead.
 */
export class LowIntervalLimitFilter {
  apply(voicings: VoicedHarmony[], layers: TextureLayer[]): VoicedHarmony[] {
    const byRole = new Map(layers.map((layer) => [layer.role, layer]));
    return voicings.map((harmony) => {
      const chosen = [...harmony.pitches];
      let compliant = true;
      for (let i = 1; i < chosen.length; i++) {
        while (chosen[i - 1] < 48 && chosen[i] < 48 && !isZoneCompliantInterval(chosen[i - 1], chosen[i])) {
          const raised = chosen[i] + 12;
          const high = i < harmony.voices.length ? (byRole.get(harmony.voices[i].role)?.range.high ?? 127) : 127;
          if (raised <= high) {
            chosen[i] = raised;
            // Cascade: a raise may collide with the next voice.
            for (let j = i + 1; j < chosen.length && chosen[j] < chosen[j - 1]; j++) {
              const cascadeHigh = byRole.get(harmony.voices[j].role)?.range.high ?? 127;
              if (chosen[j - 1] + 1 <= cascadeHigh) chosen[j] = chosen[j - 1] + 1;
              else { compliant = false; break; }
            }
          } else {
            compliant = false;
            break;
          }
        }
      }
      return { ...harmony, pitches: chosen, voices: harmony.voices.map((voice, i) => ({ ...voice, pitch: chosen[i] })), lowIntervalCompliant: compliant };
    });
  }
}

export interface VoiceLeadingResult {
  voicings: VoicedHarmony[];
  totalTravel: number;
  parallelIntervals: Array<{ fromTime: number; toTime: number; voices: [number, number]; interval: number }>;
  /** Module 5: per-chord-transition audit records (voicing ids in the spec map to slice times). */
  transitions: VoiceLeadingTransition[];
}
export interface VoiceLeadingTransition {
  fromTime: number; // spec's voicing ids map to slice times (VoicedHarmony has no id)
  toTime: number;
  voiceMovementSemitones: number[]; // per-voice delta, to − from
  totalStepCost: number;
  hasParallelFifthsOrEighths: boolean;
  isContraryOuterMotion: boolean;
  score: number;
}
/** Stage 5: retain common tones, minimize motion, encourage contrary outer motion and report parallels.
 *
 * Parallel-5th/octave penalty applies only BETWEEN the five semantic voices; same-role
 * instrument doublings/unisons — including octave doublings across e.g. Violins I/II — are
 * deliberate orchestration and exempt from the penalty (spec tag OCTAVE_DOUBLING; the future
 * native engine can key these off `unisonBlendingGroup` in instrument_db.json). No penalty
 * change accompanies this exemption: it is documentary.
 *
 * Module 5 is fully deterministic: NO randomness anywhere, NO new RNG salt.
 *
 * VoiceLeadingConfig → internal cost mapping (normalizers preserve legacy magnitudes at defaults):
 *   const wStep = config.weightStepMinimization;                  // 1.0  → identical
 *   const pCommon = config.weightCommonToneRetention * 12_500;    // 0.8  → 10_000
 *   const pContrary = (config.weightContraryMotion / 0.6) * 8;    // 0.6  → 8
 *   const pParallel = config.penaltyParallelFifths * 10_000;      // 100  → 1_000_000
 *   const pLowInterval = config.penaltyLowIntervalViolation;      // 200 (new soft term)
 */
export class VoiceLeadingOptimizer {
  optimize(input: VoicedHarmony[], layers: TextureLayer[], config: VoiceLeadingConfig = DEFAULT_VOICE_LEADING_CONFIG): VoiceLeadingResult {
    const layersByRole = new Map(layers.map((layer) => [layer.role, layer]));
    const output: VoicedHarmony[] = [];
    const transitions: VoiceLeadingTransition[] = [];
    let totalTravel = 0;
    const parallelIntervals: VoiceLeadingResult["parallelIntervals"] = [];
    const minimumSpacing = [0, 7, 7, 3, 3];
    // Config → internal cost mapping. Normalizers preserve legacy magnitudes at defaults.
    const wStep = config.weightStepMinimization;                       // 1.0  → identical
    const pCommon = config.weightCommonToneRetention * 12_500;         // 0.8  → 10_000
    const pContrary = (config.weightContraryMotion / 0.6) * 8;         // 0.6  → 8
    const pParallel = config.penaltyParallelFifths * 10_000;           // 100  → 1_000_000
    const pLowInterval = config.penaltyLowIntervalViolation;           // 200 (new soft term)

    for (const source of input) {
      const previous = output.at(-1);
      if (!previous) {
        output.push(source);
        continue;
      }

      const candidatesByVoice = source.voices.map((voice, index) => {
        const layer = layersByRole.get(voice.role);
        const low = voice.role === "BASS" ? 24 : (layer?.range.low ?? 24);
        const high = voice.role === "BASS" ? 47 : (layer?.range.high ?? 108);
        const tones = voice.role === "BASS" ? [source.bassPitchClass] : uniq([...source.pitchClasses, source.bassPitchClass]);
        const candidates = tones.flatMap((tone) => {
          const first = Math.ceil((low - tone) / 12);
          const last = Math.floor((high - tone) / 12);
          return Array.from({ length: Math.max(0, last - first + 1) }, (_, i) => tone + 12 * (first + i));
        }).filter((pitch) => pitch >= 0 && pitch <= 127
          && (voice.role === "BASS" || pitch >= 48 || pc(pitch) === source.bassPitchClass));
        const oldPitch = previous.pitches[index];
        const commonHold = source.commonTones.includes(pc(oldPitch)) && candidates.includes(oldPitch) ? [oldPitch] : [];
        return [...new Set([...commonHold, ...candidates])]
          .sort((a, b) => {
            const aCommon = commonHold.includes(a) ? -100 : 0;
            const bCommon = commonHold.includes(b) ? -100 : 0;
            return aCommon + Math.abs(a - oldPitch) + 0.15 * Math.abs(a - source.pitches[index])
              - bCommon - Math.abs(b - oldPitch) - 0.15 * Math.abs(b - source.pitches[index]);
          }).slice(0, 10);
      });

      const previousGuideTonePcs = new Set([
        ...source.guideTones,
        pc(source.rootPitchClass + 10), // 7th above root
        pc(source.rootPitchClass + 11), // maj7 above root
        pc(source.rootPitchClass + 6),  // tritone above root
      ]);
      const chosen: number[] = [];
      let best: number[] | null = null;
      let bestCost = Number.POSITIVE_INFINITY;
      const visit = (index: number, cost: number) => {
        if (cost >= bestCost) return;
        if (index === source.voices.length) {
          best = [...chosen];
          bestCost = cost;
          return;
        }
        const oldPitch = previous.pitches[index];
        const previousMotion = oldPitch - (output.length > 1 ? output[output.length - 2].pitches[index] : oldPitch);
        for (const pitch of candidatesByVoice[index]) {
          if (index > 0 && pitch < chosen[index - 1] + (minimumSpacing[index] ?? 3)) continue;
          // Module 5 zone constraint: below C3, adjacent low voices may only form
          // octaves/sub-bass or P4/P5/octaves mid-bass. Candidate-level hard rule so
 // the optimizer's report stays honest with the stage-4.5 repair.
          if (index >= 1 && chosen[index - 1] < 48 && pitch < 48 && !isZoneCompliantInterval(chosen[index - 1], pitch)) continue;
          let penalty = 0;
          if (source.commonTones.includes(pc(oldPitch)) && pitch !== oldPitch) penalty += pCommon;
          const motion = pitch - oldPitch;
          if (Math.abs(previousMotion) > 5 && !(Math.abs(motion) >= 1 && Math.abs(motion) <= 2 && Math.sign(motion) === -Math.sign(previousMotion))) {
            penalty += 10000;
          }
          // Leading-tone/dissonance resolution (soft): a voice that HAD a 7th or tritone
          // color should move by step (1–2 semitones); not stepping away incurs half the
 // low-interval penalty. Soft on purpose — hard-pruning could make the search infeasible.
          const previousPc = pc(oldPitch);
          if (previousGuideTonePcs.has(previousPc) && !(Math.abs(motion) === 1 || Math.abs(motion) === 2)) {
            penalty += pLowInterval * 0.5; 
          }
          for (let lower = 0; lower < index; lower++) {
            const priorInterval = pc(previous.pitches[index] - previous.pitches[lower]);
            const nextInterval = pc(pitch - chosen[lower]);
            const lowerMotion = chosen[lower] - previous.pitches[lower];
            if ((priorInterval === 0 || priorInterval === 7) && priorInterval === nextInterval
              && motion !== 0 && lowerMotion !== 0 && Math.sign(motion) === Math.sign(lowerMotion)) penalty += pParallel;
          }
          if (index === source.voices.length - 1 && chosen[0] !== undefined) {
            const bassMotion = chosen[0] - previous.pitches[0];
            if (bassMotion !== 0 && motion !== 0 && Math.sign(bassMotion) === Math.sign(motion)) penalty += pContrary;
          }
          chosen[index] = pitch;
          visit(index + 1, cost + wStep * (Math.abs(motion) + 0.15 * Math.abs(pitch - source.pitches[index])) + penalty);
          chosen.length = index;
        }
      };
      visit(0, 0);

      const pitches = best ?? source.voices.map((voice, index) => {
        const range = voice.role === "BASS" ? { low: 24, high: 47 } : (layersByRole.get(voice.role)?.range ?? { low: 24, high: 108 });
        return pitchInClass(voice.role === "BASS" ? source.bassPitchClass : source.rootPitchClass, range, previous.pitches[index]);
      });
      let hasParallel = false;
      for (let lower = 0; lower < pitches.length; lower++) for (let upper = lower + 1; upper < pitches.length; upper++) {
        const priorInterval = pc(previous.pitches[upper] - previous.pitches[lower]);
        const nextInterval = pc(pitches[upper] - pitches[lower]);
        const upperMotion = pitches[upper] - previous.pitches[upper];
        const lowerMotion = pitches[lower] - previous.pitches[lower];
        if ((priorInterval === 0 || priorInterval === 7) && priorInterval === nextInterval
          && upperMotion !== 0 && lowerMotion !== 0 && Math.sign(upperMotion) === Math.sign(lowerMotion)) {
          parallelIntervals.push({ fromTime: previous.startTime, toTime: source.startTime, voices: [lower, upper], interval: priorInterval });
          hasParallel = true;
        }
      }
      const bassMotionFinal = pitches[0] - previous.pitches[0];
      const leadMotionFinal = pitches[pitches.length - 1] - previous.pitches[pitches.length - 1];
      transitions.push({
        fromTime: previous.startTime,
        toTime: source.startTime,
        voiceMovementSemitones: pitches.map((pitch, i) => pitch - previous.pitches[i]),
        totalStepCost: bestCost === Number.POSITIVE_INFINITY ? 0 : bestCost,
        hasParallelFifthsOrEighths: hasParallel,
        isContraryOuterMotion: bassMotionFinal !== 0 && leadMotionFinal !== 0 && Math.sign(bassMotionFinal) === -Math.sign(leadMotionFinal),
        score: bestCost === Number.POSITIVE_INFINITY ? 0 : bestCost,
      });
      pitches.forEach((pitch, voiceIndex) => { totalTravel += Math.abs(pitch - previous.pitches[voiceIndex]); });
      output.push({ ...source, pitches, voices: source.voices.map((voice, voiceIndex) => ({ ...voice, pitch: pitches[voiceIndex] })) });
    }
    return { voicings: output, totalTravel, parallelIntervals, transitions };
  }
}

/** Stage 6: validate ranges and convert concert pitch to written pitch. */
export class InstrumentRangeFilter {
  /** Sentimented velocity texture (applied per event); lets the composition seed color dynamics without altering structure. */
  private texture?: () => number;

  constructor(texture?: () => number) {
    this.texture = texture;
  }

  apply(voicings: VoicedHarmony[], layers: TextureLayer[], profiles: InstrumentProfile[]): AbstractNoteEvent[] {
    const layersByRole = new Map(layers.map((layer) => [layer.role, layer]));
    const events: AbstractNoteEvent[] = [];
    for (const harmony of voicings) {
      for (const voice of harmony.voices) {
        const layer = layersByRole.get(voice.role)!;
        // Polyphony hotfix: one event per UNIQUE instrument per voice slot. The
        // allocator repeats a single section id across voice slots (e.g. a 4-voice
        // viola section as [violas, violas, violas, violas]); emitting per slot
        // stacked 4 identical unisons on one wind track — impossible for one player.
        // De-duplicate here; section UNISONS across distinct instruments remain.
        for (const instrumentId of [...new Set(layer.instrumentIds)]) {
          const profile = profiles.find((candidate) => candidate.id === instrumentId);
          const range = profile?.writtenRange ?? layer.range;
          const comfortable = profile?.comfortableRange ?? range;
          const pitchConcert = pitchInClass(pc(voice.pitch), comfortable, voice.pitch);
          const offset = (profile?.transpositionSemitones ?? 0) + (profile?.clefShiftSemitones ?? 0);
          const pitchWritten = clamp(pitchConcert + offset, range.low, range.high);
          const registerOffset = pitchConcert < 48 ? -0.03 : pitchConcert > 84 ? 0.025 : 0;
          const texture = this.texture ? (this.texture() - 0.5) * 0.1 : 0;
          events.push({ instrumentId, pitchConcert, pitchWritten, startTime: harmony.startTime,
            duration: harmony.duration, normalizedDynamic: clamp(harmony.energy + (profile?.dynamicOffset ?? 0) + registerOffset + texture, 0, 1),
            semanticArticulation: layer.articulation, role: voice.role });
        }
      }
      const pad = layersByRole.get("PAD")!;
      if (!pad.instrumentIds.length) continue;
      // Polyphony hotfix Phase 3: uncovered chord tones scatter ROUND-ROBIN across
      // the pad's instruments instead of stacking vertically on the first one.
      // A string profile keeps at most 2 PAD tones (double-stop ceiling); overflow
      // goes to keyboard profiles (piano/harp) when present — vertical stacks belong
      // on keyboards — and is otherwise DROPPED (never pushed onto winds/brass).
      const padProfiles = pad.instrumentIds.map((id) => profiles.find((item) => item.id === id)).filter((item): item is InstrumentProfile => item !== undefined);
      const stringPads = padProfiles.filter((item) => item.family === "strings");
      const keyboardPads = padProfiles.filter((item) => item.family === "keys");
      let padCursor = 0;
      for (const tone of harmony.pitchClasses) {
        if (harmony.voices.some((voice) => voice.role === "PAD" && pc(voice.pitch) === tone)) continue;
        let chosen: InstrumentProfile | undefined;
        if (stringPads.length) {
          const roundRobin = stringPads[padCursor % stringPads.length]!;
          // String pads accept at most 2 tones each (double-stop); overflow → keyboards.
          const assigned = events.filter((event) => event.role === "PAD" && event.instrumentId === roundRobin.id
            && event.startTime < harmony.startTime + harmony.duration && harmony.startTime < event.startTime + event.duration).length;
          chosen = assigned < 2 ? roundRobin : keyboardPads[0];
          padCursor++;
        } else {
          chosen = keyboardPads[padCursor % Math.max(1, keyboardPads.length)];
          padCursor++;
        }
        if (!chosen) continue; // overflow with no keyboard available: dropped
        const padRange = chosen.comfortableRange ?? { low: pad.range.low, high: pad.range.high };
        const pitchConcert = pitchInClass(tone, padRange, 67);
        const offset = (chosen.transpositionSemitones ?? 0) + (chosen.clefShiftSemitones ?? 0);
        events.push({ instrumentId: chosen.id, pitchConcert,
          pitchWritten: clamp(pitchConcert + offset, chosen.writtenRange.low, chosen.writtenRange.high),
          startTime: harmony.startTime, duration: harmony.duration,
          normalizedDynamic: clamp(harmony.energy + (chosen.dynamicOffset ?? 0), 0, 1),
          semanticArticulation: pad.articulation, role: "PAD" });
      }
    }
    return events.sort((a, b) => a.startTime - b.startTime || a.pitchConcert - b.pitchConcert);
  }
}

/** Six sequential semantic stages, with no MIDI or plugin concerns. */
export function generateOrchestralScore(config: ProjectConfig, chords: ChordBlock[], sections: StructureSection[], options: PipelineOptions = {}): AbstractOrchestralScore {
  const profiles = options.profiles ?? DEFAULT_INSTRUMENT_PROFILES;
  const effectiveChords = chords.length
    ? chords
    : [{
        startTime: 0,
        duration: Math.max(16 * ((PPQ * 4 * config.timeSignature[0]) / config.timeSignature[1]), ...sections.map((section) => section.startTime + section.duration)),
        rootPitchClass: pc(config.keyRoot),
        quality: MODE_INTERVALS[normalizeMode(config.scaleMode)].includes(3) ? "Min" as const : "Maj" as const,
        extensions: [],
      }];
  const stage1 = new HarmonicParser().parse(config, effectiveChords);
  const stage2 = new DynamicMappingEngine().map(stage1, sections, config, profiles);
  const variation = options.seed === undefined ? undefined : mulberry32(options.seed + 0x5f3a);
  const stage3 = new TextureRoleAllocator().allocate(config, stage2, profiles, variation);
  const availableFamilies = new Set(profiles.map((profile) => profile.family).filter((family): family is string => Boolean(family)));
  const allowedGroups = new Set(stage2.flatMap((point) => point.activeGroups));
  const stage3Layers = stage3.map((layer) => {
    const available = layer.instrumentIds.flatMap((id) => {
      const profile = profiles.find((candidate) => candidate.id === id);
      return profile ? [profile] : [];
    });
    const selectedFamily = profiles.find((profile) => profile.id === layer.instrumentIds[0])?.family;
    const permitted = selectedFamily !== undefined && availableFamilies.has(selectedFamily) && allowedGroups.has(selectedFamily);
    if (!permitted || !available.length) return { ...layer, instrumentIds: [] };
    if (available.length < 2) return layer;
    // Preserve the assigned order, which may already be seed-rotated; only extend with profiles that are missing.
    const assignedIds = layer.instrumentIds.filter((id) => available.some((profile) => profile.id === id));
    const extra = available.filter((profile) => !assignedIds.includes(profile.id)).map((profile) => profile.id);
    return {
      ...layer,
      instrumentIds: [...assignedIds, ...extra],
      range: {
        low: Math.min(...available.map((profile) => profile.comfortableRange?.low ?? profile.writtenRange.low)),
        high: Math.max(...available.map((profile) => profile.comfortableRange?.high ?? profile.writtenRange.high)),
      },
    };
  });
  for (const profile of profiles) {
    if (DOUBLING_ONLY_PROFILE_ROLES.has(profile.role ?? "")) continue;
    const family = profile.family;
    if (!family || !allowedGroups.has(family) || stage3Layers.some((layer) => layer.instrumentIds.includes(profile.id))) continue;
    const targetRole: SemanticRole = family === "brass" ? "COUNTERLINE" : family === "woodwinds" ? "LEAD" : family === "percussion" ? "OSTINATO" : "PAD";
    const target = stage3Layers.find((layer) => layer.role === targetRole);
    if (target) target.instrumentIds.push(profile.id);
  }
  const activeLayers = stage3Layers.filter((layer) => layer.instrumentIds.length > 0);
  if (!activeLayers.length) return { projectConfig: config, events: [], dynamicCurves: new Map() };
  for (const layer of activeLayers) {
    const profile = profiles.find((candidate) => candidate.id === layer.instrumentIds[0]);
    if (profile) layer.range = profile.comfortableRange ?? profile.writtenRange;
  }
  const stage4 = new OvertoneSpacingFilter().apply(stage1, activeLayers, stage2, options.voicingAlgorithm);
  // Stage 4.5: overtone-zone interval repair between spacing and voice-leading (deterministic; no RNG).
  const spaced = new LowIntervalLimitFilter().apply(stage4, activeLayers);
  const stage5 = new VoiceLeadingOptimizer().optimize(spaced, activeLayers, options.voiceLeadingConfig);
  const events = new InstrumentRangeFilter(variation).apply(stage5.voicings, activeLayers, profiles);
  const dynamicCurves = new Map<string, DynamicPoint[]>();
  for (const layer of activeLayers) for (const id of layer.instrumentIds) dynamicCurves.set(id, stage2.map(({ time, value }) => ({ time, value })));
  return { projectConfig: config, events, dynamicCurves };
}

function activeFamiliesHas(groups: Project["generationSettings"] extends infer T ? NonNullable<T> extends { orchestration: infer O } ? O extends { enabledGroups: infer G } ? G : never : never : never, family: string): boolean {
  if (family === "strings") return groups.strings;
  if (family === "brass") return groups.brass;
  if (family === "woodwinds") return groups.woodwinds;
  if (family === "percussion") return groups.percussion || groups.rhythm;
  if (family === "keys") return groups.rhythm;
  return false;
}

function qualityForChord(quality: ParsedChordQuality): ChordBlockQuality {
  if (["minor", "m7", "m7b5", "m6", "m9"].includes(quality)) return "Min";
  if (["diminished", "dim7"].includes(quality)) return "Dim";
  if (["augmented", "aug7"].includes(quality)) return "Aug";
  if (quality === "sus2") return "Sus2";
  if (quality === "sus4" || quality === "7sus4") return "Sus4";
  return "Maj";
}
function typeForSection(name: string): SectionType {
  const normalized = normalizeName(name);
  if (normalized.includes("prechorus")) return "PreChorus";
  if (normalized.includes("chorus")) return "Chorus";
  if (normalized.includes("intro")) return "Intro";
  if (normalized.includes("build")) return "Build";
  if (normalized.includes("break")) return "Breakdown";
  if (normalized.includes("outro")) return "Outro";
  return "Verse";
}
function densityForSection(type: SectionType): StructureSection["densityLevel"] {
  return type === "Chorus" ? "Tutti" : type === "Build" || type === "PreChorus" ? "Dense" : type === "Intro" || type === "Breakdown" ? "Sparse" : "Balanced";
}
function transformGeneratedNotes(notes: Note[], track: Track, project: Project, options: GenerateOptions, humanization: HumanizationSettings): Note[] {
  const intensity = clamp((options.humanizeIntensity ?? humanization.intensity) / 100, 0, 1);
  const applyHumanize = options.humanize && (intensity > 0 || (options.rubato ?? humanization.rubato) > 0);
  const transformed = applyHumanize ? humanizeNotes(notes, project.bpm, options.seed + track.midiChannel, intensity, options.rubato ?? humanization.rubato) : notes;
  return transformed.map((note) => {
    let startTick = note.startTick;
    if (humanization.latencyCompensation && (options.latencyCompensation ?? true)) {
      const ms = options.latencyCompensationMs?.[track.role] ?? options.latencyCompensationMs?.[track.family] ?? options.latencyCompensationMs?.custom ?? humanization.latencyCompensationMs?.[track.role] ?? humanization.latencyCompensationMs?.[track.family] ?? humanization.latencyCompensationMs?.custom ?? 0;
      startTick = Math.max(0, startTick - msToTicks(ms, project.bpm));
    }
    const rng = mulberry32(options.seed + track.midiChannel + note.startTick + note.pitch);
    const cents = Math.max(0, Math.min(15, options.intonationCents ?? humanization.intonationCents));
    const detuneCents = cents ? Math.round((rng() * 2 - 1) * cents * 100) / 100 : 0;
    return { ...note, detuneCents, startTick: Math.max(0, Math.round(startTick)) };
  });
}

export function projectProfiles(project: Project): InstrumentProfile[] {
  const databaseProfiles = buildPipelineProfiles();
  return project.tracks.filter((track) => track.family !== "structure" && track.family !== "audio" && track.family !== "percussion").flatMap((track) => {
    const db = databaseProfileForPipelineRole(track.role);
    const pipeline = databaseProfiles.find((profile) => profile.id === dbInstrumentIdForPipelineRole(track.role));
    if (db && pipeline) return [{ ...pipeline, id: track.id }];
    return [{
      id: track.id,
      role: track.role,
      family: track.family,
      writtenRange: { low: track.lowestNote, high: track.highestNote },
      comfortableRange: { low: track.lowestNote, high: track.highestNote },
      transpositionSemitones: track.role === "horns" ? 7 : track.role === "clarinets" || track.role === "trumpets" ? 2 : 0,
      carryingPowerWeight: track.role === "harp" ? 0.35 : track.role === "piano" ? 0.6 : undefined,
    }];
  });
}

