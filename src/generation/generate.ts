export interface EfgSwitches { germ: boolean; nct: boolean; counterline: boolean }

/** Phase 0 roles contract: engines ACTIVE for a role remove it from realizeRhythm.
 * LEAD is owned by E+F when either runs; COUNTERLINE/OSTINATO by G; BASS/PAD always
 * remain realizeRhythm's. Engines fully OFF callers pass no roles at all (legacy). */
export function efgRealizeRoles(switches: EfgSwitches): SemanticRole[] {
  return [
    ...((switches.germ || switches.nct) ? [] : ["LEAD" as const]),
    ...(!switches.counterline ? ["COUNTERLINE" as const, "OSTINATO" as const] : []),
    "BASS" as const,
    "PAD" as const,
  ];
}

/** Deterministic per-beat energy for the theme engine: harmonic parser tension
 * aligned to the beat grid (0..0.7), 0.25 fallback outside chords. No RNG. */
export function buildEfgEnergies(config: ProjectConfig, chords: ChordBlock[]): number[] {
  const beatTicks = (PPQ * 4) / config.timeSignature[1];
  const totalTicks = Math.max(...chords.map((block) => block.startTime + block.duration), 0);
  const beatCount = Math.ceil(totalTicks / beatTicks) + 1;
  const parsed = new HarmonicParser().parse(config, chords);
  return Array.from({ length: beatCount }, (_, index) => parsed[index]?.tension ?? 0.25);
}

/** Addendum E→F→G engine chain, the single wiring point shared by generate() and
 * the A/B test harness. Order is fixed: E (theme, salt 0xe551) replaces the LEAD
 * grid → F (NCT pass, salt 0xf0c8) decorates that finished lead → G (cells, salt
 * 0x6066) owns COUNTERLINE/OSTINATO wholesale and may approach bass targets.
 * Deterministic per (events, ctx, seed, switches); every disabled engine must
 * behave byte-identically to a run where the engine never exists. */
export function applyEfgEngines(
  events: AbstractNoteEvent[],
  ctx: EfgEngineContext,
  seed: number,
  switches: EfgSwitches,
): { events: AbstractNoteEvent[]; applied: EfgSwitches & { leadReplaced: boolean } } {
  let current = events;
  const byStart = (a: AbstractNoteEvent, b: AbstractNoteEvent) => a.startTime - b.startTime || a.pitchConcert - b.pitchConcert;

  // E — theme engine: replaces the LEAD grid wholesale (salt 0xe551, internal).
  if (switches.germ) {
    const leadEvents = current.filter((event) => event.role === "LEAD");
    const leadInstrumentIds = [...new Set(leadEvents.map((event) => event.instrumentId))];
    const leadProfile = ctx.profiles.find((profile) => profile.id === leadInstrumentIds[0])
      ?? ctx.profiles.find((profile) => profile.family === "woodwinds");
    if (leadProfile) {
      const themeCtx: ThemeContext = {
        config: ctx.config,
        chords: ctx.chords as ResolvedChordBlock[],
        sections: ctx.sections,
        energies: ctx.energies,
        chordStartTimes: ctx.chordStartTimes,
        profiles: ctx.profiles,
        leadInstrumentIds,
        leadRange: { low: leadProfile.comfortableRange?.low ?? leadProfile.writtenRange.low, high: leadProfile.comfortableRange?.high ?? leadProfile.writtenRange.high },
        enabled: { germ: true },
        intensityAt: ctx.intensityAt,
        subdivisionCapAt: ctx.subdivisionCapAt,
      };
      const theme = applyThemeEngine(current, themeCtx, seed);
      if (theme.regenerated) current = theme.events;
    }
  }

  // F — NCT pass (salt 0xf0c8, internal): decorates the FINISHED lead stream.
  if (switches.nct) {
    const leadSlice = current.filter((event) => event.role === "LEAD");
    if (leadSlice.length) {
      const others = current.filter((event) => event.role !== "LEAD");
      const nct = applyNctPass(leadSlice, { mode: normalizeMode(ctx.config.scaleMode), keyRoot: ctx.config.keyRoot, bpm: ctx.config.baseBpm }, seed, { intensityAt: ctx.intensityAt });
      current = [...others, ...nct.events].sort(byStart);
    }
  }

  // G — counterline/ostinato cells + bass approach (salt 0x6066, internal);
  // replaces COUNTERLINE/OSTINATO wholesale (Phase 0), reproduces BASS unless it
  // inserts approach tones.
  if (switches.counterline) {
    const leadInstrumentIds = new Set(current.filter((event) => event.role === "LEAD").map((event) => event.instrumentId));
    const bandOverlap = (profile: InstrumentProfile, low: number, high: number): boolean => {
      const band = profile.comfortableRange ?? profile.writtenRange;
      return band.high >= low && band.low <= high;
    };
    // G.2/G.4 spec pools: counterline = viola/cello/horn/clarinet mid register;
    // ostinato = low strings + keyboard safe band. Never the LEAD instruments.
    const counterlineProfiles = ctx.profiles.filter((profile) =>
      ["violas", "cellos", "horns", "clarinets"].includes(profile.role ?? "") && bandOverlap(profile, 48, 67) && !leadInstrumentIds.has(profile.id));
    const ostinatoProfiles = ctx.profiles.filter((profile) =>
      ["violins2", "violas", "cellos", "harp", "piano"].includes(profile.role ?? "") && bandOverlap(profile, 43, 64) && !leadInstrumentIds.has(profile.id));
    const bassEvent = current.find((event) => event.role === "BASS");
    const bassProfile = bassEvent ? ctx.profiles.find((profile) => profile.id === bassEvent.instrumentId) : undefined;
    current = applyCounterlineEngine(current, {
      timeSignature: ctx.config.timeSignature,
      keyRoot: ctx.config.keyRoot,
      mode: ctx.config.scaleMode,
      chords: ctx.chords,
      sections: ctx.sections.map((section) => ({ startTime: section.startTime, duration: section.duration, energy: section.targetDynamic ?? 0.55 })),
      counterlineProfiles,
      ostinatoProfiles,
      bassProfile,
      events: current,
      leadNotes: current.filter((event) => event.role === "LEAD").map((event) => ({ startTime: event.startTime, pitch: event.pitchConcert, duration: event.duration })),
      counterlineEnabled: true,
      ostinatoEnabled: true,
      bassApproachEnabled: true,
      intensityAt: ctx.intensityAt,
      subdivisionCapAt: ctx.subdivisionCapAt,
    }, seed);
  }

  // Module 8.5 — arrangement intelligence: seeded role rotation (casting spent
  // 0x8a55 pre-pipeline in planRotation; this pass is deterministic) + active
  // masks. Between the cell engine and Stage 6.5 — BEFORE doubling so doubles
  // attach to the FINAL carriers, BEFORE articulation/dynamics so register
  // logic sees the final written pitches. Rotation-off = this block never runs.
  if (ctx.rotation) {
    current = applyRoleRotation(current, ctx.rotation.plan, ctx.profiles);
    current = applyActiveMask(current, ctx.rotation.plan, ctx.rotation.measures, ctx.rotation.config, ctx.profiles, ctx.rotation.exposedRoles);
  }

  return { events: current, applied: { ...switches, leadReplaced: switches.germ } };
}

/** Semantic-stage input builder shared VERBATIM by generate() and the E/F/G
 * diagnostics scripts, so engine metrics are measured against the true pipeline
 * (single wiring point). Includes the wiring-stamped chords (resolvedPcs) —
 * pure data, no RNG. */
export function buildSemanticInputs(
  project: Project,
  generationSettings: ProjectGenerationSettings,
  seed: number,
): {
  config: ProjectConfig;
  chords: ChordBlock[];
  arrangement: Parameters<typeof arrangementContext>[1];
  arrangementInfo: ReturnType<typeof arrangementContext>;
  scoreSections: StructureSection[];
  compositionProfiles: InstrumentProfile[];
  selectedVoicing: VoicingAlgorithm;
  voiceLeadingConfig: VoiceLeadingConfig;
  score: AbstractOrchestralScore;
} {
  const orchestration = generationSettings.orchestration;
  const config: ProjectConfig = { keyRoot: project.key, scaleMode: project.mode, baseBpm: project.bpm,
    timeSignature: [project.timeSignature.numerator, project.timeSignature.denominator], presetStyle: generationSettings.orchestralStyle };
  const chords = project.chords.map((chord) => {
    const parsed = parseChord(chord.symbol);
    const symbol = parsed.ok ? parsed.chord : null;
    const block = { startTime: chord.startTick, duration: chord.durationTicks, rootPitchClass: symbol?.root ?? project.key,
      quality: chord.quality ?? qualityForChord(symbol?.quality ?? "major"), extensions: chord.extensions ?? symbol?.extensions ?? [],
      bassOverride: chord.bassOverride ?? symbol?.bass ?? undefined, symbol: chord.symbol } satisfies ChordBlock;
    // Stamp resolved pitch classes (root/3rd/5th inclusive, parse-accurate) additively;
    // pure data, no RNG — engine-off output stays byte-identical by construction.
    const parsedBlock = block.symbol ? parseChord(block.symbol) : { ok: false } as const;
    const resolvedPcs = parsedBlock.ok ? [...new Set(parsedBlock.chord.pitchClasses)].sort((a, b) => a - b) : chordIntervals(block).map((interval) => pc(block.rootPitchClass + interval)).sort((a, b) => a - b);
    return { ...block, resolvedPcs } satisfies ChordBlock;
  });
  // Module 8 PRE-pipeline: deterministic measure profiles + virtual build tiling.
  // Staggering is DATA-IN (stage 2's groupFor/DENSITY_VALUES mappings are untouched —
  // the virtual 2-bar slices exploit them through section targetDynamic/densityLevel).
  const arrangement = { ...DEFAULT_ARRANGEMENT_CONFIG, ...generationSettings.arrangement };
  const arrangementInfo = arrangementContext(project, arrangement);
  const scoreSections = expandSectionsForStaggering(
    project.sections,
    arrangement,
  ).flatMap((section) => {
    const type = typeForSection(section.name);
    return [{ startTime: barToTick(section.startBar, project.timeSignature), duration: section.lengthBars * ticksPerBar(project.timeSignature),
      type, targetDynamic: section.targetDynamic ?? BASE_DYNAMICS[type], densityLevel: section.densityLevel ?? densityForSection(type) } satisfies StructureSection];
  });
  const enabledFamilies = new Set<string>([
    ...(orchestration.enabledGroups.strings ? ["strings"] : []),
    ...(orchestration.enabledGroups.brass ? ["brass"] : []),
    ...(orchestration.enabledGroups.woodwinds ? ["woodwinds"] : []),
    ...(orchestration.enabledGroups.percussion ? ["percussion"] : []),
    ...(orchestration.enabledGroups.rhythm ? ["keys"] : []),
  ]);
  const styleWeights = ORCHESTRAL_STYLE_WEIGHTS[generationSettings.orchestralStyle];
  const weightedProfiles = projectProfiles(project).map((profile) => ({
    ...profile,
    dynamicOffset: (profile.dynamicOffset ?? 0) + (1 - (styleWeights[profile.family === "keys" ? "rhythm" : (profile.family as keyof typeof styleWeights)] ?? 1)) * -0.15,
  }));
  const activeProfiles = weightedProfiles.filter((profile) => enabledFamilies.has(profile.family ?? ""));
  const compositionProfiles = activeProfiles.map((profile) => {
    const size = profile.family === "woodwinds" ? orchestration.woodwindsSize === "Threes + Auxiliaries" ? 3 : orchestration.woodwindsSize === "Chamber Ensemble" ? 1 : 2
      : profile.family === "brass" ? orchestration.brassSize === "Cinematic Double Brass" ? 2 : 1
      : profile.family === "strings" ? orchestration.stringsSize === "Full Symphonic (16/14/12/10/8)" ? 2 : orchestration.stringsSize === "Medium Studio" ? 1 : 0.5 : 1;
    return { ...profile, dynamicOffset: (profile.dynamicOffset ?? 0) + Math.log2(size) * 0.04 };
  });
  const selectedVoicing = orchestration.voicingStyle;
  const voiceLeadingConfig = { ...DEFAULT_VOICE_LEADING_CONFIG, ...(generationSettings.orchestration?.voiceLeadingConfig ?? {}) };
  const score = generateOrchestralScore(config, chords, scoreSections, { seed, profiles: compositionProfiles, voicingAlgorithm: selectedVoicing, voiceLeadingConfig });
  return { config, chords, arrangement, arrangementInfo, scoreSections, compositionProfiles, selectedVoicing, voiceLeadingConfig, score };
}

/** Compatibility adapter used by the current arranger UI; semantics are converted into editable notes. */
export function generate(project: Project, options: GenerateOptions): Track[] {
  const generationSettings = project.generationSettings ?? DEFAULT_GENERATION_SETTINGS;
  const orchestration = generationSettings.orchestration;
  const humanization = generationSettings.humanization;
  const inputs = buildSemanticInputs(project, generationSettings, options.seed);
  const { config, arrangement, arrangementInfo, scoreSections, compositionProfiles, score } = inputs;
  const chords = inputs.chords;
  // Addendum E/F/G — Addendum E (theme, salt 0xe551) → F (NCT pass, salt 0xf0c8) →
  // G (counterline/ostinato cells + bass approach, salt 0x6066), run in that ORDER
  // before Stage 6.5. Controls come from generationSettings.themes; every absent
  // knob defaults ON (A/B switches), and ALL-OFF must stay byte-identical to the
  // pre-E/F/G pipeline (no engine call, no RNG draw, legacy realizeRhythm path).
  const themeSwitches = {
    germ: generationSettings.themes?.germ ?? true,
    nct: generationSettings.themes?.nct ?? true,
    counterline: generationSettings.themes?.counterline ?? true,
  };
  const themesActive = themeSwitches.germ || themeSwitches.nct || themeSwitches.counterline;
  // Stamp resolved pitch classes (root/3rd/5th inclusive, parse-accurate) additively;
  // pure data, no RNG — engine-off output stays byte-identical by construction.
  const efgChords = chords;
  // Module 8.5 — arrangement intelligence. The casting plan is drawn ONCE here
  // (the ONLY RNG this module spends: 0x8a55 inside planRotation); with the
  // rotation disabled the plan is never built and every 8.5 path is a no-op.
  const rotationPartial = generationSettings.arrangement?.rotation;
  const rotationConfig = resolveRotationConfig(rotationPartial);
  const rotationPlan: RotationPlan | undefined = rotationConfig.enabled
    ? planRotation(project, rotationPartial, options.seed)
    : undefined;
  const efgRotation = rotationPlan
    ? { plan: rotationPlan, config: rotationConfig, measures: arrangementInfo.measures, exposedRoles: exposedBreakdownRoles(arrangement.breakdownExposedLayer) }
    : undefined;
  const pipelineEvents = themesActive
    ? applyEfgEngines(score.events, {
      config,
      chords: efgChords,
      sections: scoreSections,
      energies: buildEfgEnergies(config, efgChords),
      chordStartTimes: efgChords.map((block) => block.startTime),
      profiles: compositionProfiles,
      intensityAt: arrangementInfo.intensityAt,
      subdivisionCapAt: arrangementInfo.subdivisionCapAt,
      rotation: efgRotation,
    }, options.seed, themeSwitches).events
    : score.events;
  // Stage 6.5: role-appropriate rhythmic figures; independent RNG salt from the stage (0x5f3a) stream.
  // Module 8: per-measure intensity/subdivision probes feed in additively.
  // Phase 0 roles contract: engines ON ⇒ realizeRhythm only shapes BASS/PAD (LEAD is
  // owned by E+F, COUNTERLINE/OSTINATO by G); engines OFF ⇒ no roles option = legacy.
  // Roles that stay legacy (their engine off) are passed through on purpose.
  const rhythmRng = mulberry32(options.seed + 0x9e37);
  const realized = realizeRhythm(pipelineEvents, {
    rng: rhythmRng,
    beatTicks: (PPQ * 4) / project.timeSignature.denominator,
    intensity: options.density,
    intensityAt: arrangementInfo.intensityAt,
    subdivisionCapAt: arrangementInfo.subdivisionCapAt,
    ...(themesActive ? { roles: efgRealizeRoles(themeSwitches) } : {}),
  });
  const locked = new Set(options.lockedTrackIds);
  // Stage 7: articulation selection (salt 0x4a17) and stage 8: anti-machine-gun (salt 0xb0b5),
  // both after rhythm realization and before the adapter bake. Metadata only; pitches untouched.
  const articulationRng = mulberry32(options.seed + 0x4a17);
  const amgRng = mulberry32(options.seed + 0xb0b5);
  const articulationCtx = { bpm: project.bpm, timeSignature: project.timeSignature, profiles: compositionProfiles, rng: articulationRng };
  const evaluated = selectArticulations(realized, articulationCtx);
  applyAntiMachineGun(evaluated, { ...articulationCtx, rng: amgRng });
  // Stage 9: doubling + anti-flanging (salt 0xd0b1, one shared stream — doubling draws
  // first, anti-flanging second, in event order; both before the adapter bake).
  const doublingPartial = generationSettings.orchestration?.doubling;
  const doublingCfg = {
    ...DEFAULT_DOUBLING_CONFIG,
    ...doublingPartial,
    antiFlanging: { ...DEFAULT_ANTI_FLANGING, ...doublingPartial?.antiFlanging },
  };
  // Module 8.5 §4 — chorus lead brass color ships as ONE data rule in
  // DEFAULT_DOUBLING_RULES; with the rotation engine disabled it is stripped
  // again so the disabled path stays byte-identical to the pre-8.5 build.
  if (rotationPlan === undefined) {
    doublingCfg.rules = (doublingCfg.rules ?? DEFAULT_DOUBLING_RULES).filter((rule) =>
      !(rule.primaryRole === "violins1" && rule.doublingRole === "trumpets" && rule.intervalSemitones === 12 && rule.condition === "TUTTI_PEAK"));
  }
  const doublingTargets = buildPipelineProfiles().filter((profile) => ["piccolo", "doubleBass", "bassTrombone"].includes(profile.role ?? ""));
  const balanceProfiles = [...compositionProfiles, ...doublingTargets];
  // Deterministic Stage 10 windowing precedes doubling so every generated double follows the shifted melody.
  const balanceConfig = resolveBalanceConfig(orchestration.balance);
  const windowed = applyAntiphonalWindowing(evaluated, { profiles: balanceProfiles, config: balanceConfig, bpm: project.bpm });
  const doubled = doublingCfg.enabled
    ? applyAntiFlanging(
      applyDoublings(windowed, { profiles: balanceProfiles, rng: mulberry32(options.seed + 0xd0b1), config: doublingCfg }),
      { profiles: balanceProfiles, rng: mulberry32(options.seed + 0xd0b1 + 1), config: doublingCfg, bpm: project.bpm },
    )
    : windowed;
  // Module 8 POST-score: breakdown drop runs AFTER doubling/anti-flanging and
  // BEFORE attenuation/dynamics so dropped events cost nothing downstream.
  const dropped = applyBreakdownDrop(doubled as AbstractNoteEvent[], { windows: arrangementInfo.windows, config: arrangement, profiles: balanceProfiles }) as typeof doubled;
  const balanced = calculateNoteDynamics(applyAccompanimentAttenuation(dropped, { profiles: balanceProfiles, config: balanceConfig }), {
    profiles: balanceProfiles,
    config: balanceConfig,
  });
  const byTrack = new Map<string, Note[]>();
  // Anti-flange detune is baked PRE-humanization; humanization adds its own detune on top
  // (M10 reconciliation note: arithmetic composes additively, ±15 clamp enforced at export).
  for (const event of balanced) {
    const profile = balanceProfiles.find((candidate) => candidate.id === event.instrumentId);
    const family = profile?.family;
    const keyed = family !== "percussion" && family !== "keys";
    const bucket = byTrack.get(event.instrumentId) ?? [];
    const velocityBase = Math.round(20 + event.normalizedDynamic * 107);
    const registerVelocityModifier = event.dynamics?.velocityModifier ?? 0;
    bucket.push({
      pitch: clamp(event.pitchConcert, profile?.comfortableRange?.low ?? profile?.writtenRange.low ?? 0, profile?.comfortableRange?.high ?? profile?.writtenRange.high ?? 127),
      startTick: Math.max(0, event.startTime + (keyed ? (event.articulation.timingOffsetTicks ?? 0) : 0)),
      durationTicks: Math.max(1, Math.round(event.duration * event.articulation.noteDurationMultiplier)),
      velocity: clamp(Math.round(velocityBase + registerVelocityModifier + (keyed ? event.articulation.velocityOffset : 0)), 1, 127),
      // Module 8.5 semantic-role stamp for the chorus divider — ONLY when the
      // rotation engine is enabled, so rotation-off output keeps byte-identity.
      ...(rotationPlan ? { role: event.role } : {}),
      ...(event.detuneCents ? { detuneCents: event.detuneCents } : {}),
      ...(event.isDoubling || event.cc74Offset !== undefined ? { isDoubling: event.isDoubling, cc74Offset: event.cc74Offset } : {}),
      ...(event.dynamics ? { dynamics: { cc11Value: event.dynamics.cc11Value, cc74Value: event.dynamics.cc74Value, attenuationActive: event.dynamics.attenuationActive } } : {}),
      ...(keyed ? {
        technique: event.articulation.primaryTechnique,
        bowDirection: event.articulation.bowDirection,
        ...(event.bendPoints.length ? { pitchBendPoints: event.bendPoints } : {}),
      } : {}),
    });
    byTrack.set(event.instrumentId, bucket);
  }
  const returned = project.tracks.map((track) => {
    if (track.family === "structure" || track.family === "audio" || locked.has(track.id)) return { ...track, notes: track.notes.map((note) => ({ ...note })) };
    const generated = byTrack.get(track.id) ?? [];
    const notes = activeFamiliesHas(orchestration.enabledGroups, track.family) ? generated : [];
    const profile = compositionProfiles.find((candidate) => candidate.id === track.id);
    return {
      ...track,
      ...(profile ? { lowestNote: profile.comfortableRange?.low ?? profile.writtenRange.low, highestNote: profile.comfortableRange?.high ?? profile.writtenRange.high } : {}),
      notes: transformGeneratedNotes(notes, track, project, options, humanization),
    };
  });
  const existingIds = new Set(returned.map((track) => track.id));
  const existingRoles = new Set(returned.filter((track) => track.family !== "structure" && track.family !== "audio").map((track) => track.role));
  for (const [instrumentId, generatedNotes] of byTrack) {
    const profile = buildPipelineProfiles().find((candidate) => candidate.id === instrumentId);
    if (existingIds.has(instrumentId) || !generatedNotes.length || !profile?.role || existingRoles.has(profile.role as Track["role"])) continue;
    if (!profile.family) continue;
    const family = profile.family as Track["family"];
    const template = project.tracks.find((track) => track.family === family);
    if (!template) continue;
    const generatedTrack: Track = {
      ...template,
      id: instrumentId,
      name: profile.displayName ?? profile.role.replace(/([A-Z])/g, " $1").replace(/^./, (value) => value.toUpperCase()),
      role: profile.role as Track["role"],
      lowestNote: profile.writtenRange.low,
      highestNote: profile.writtenRange.high,
      midiChannel: (returned.filter((track) => track.family !== "structure" && track.family !== "audio").length % 16) + 1,
      notes: transformGeneratedNotes(generatedNotes, { ...template, id: instrumentId, midiChannel: (returned.filter((track) => track.family !== "structure" && track.family !== "audio").length % 16) + 1, role: profile.role as Track["role"], family, lowestNote: profile.writtenRange.low, highestNote: profile.writtenRange.high }, project, options, humanization),
    };
    returned.push(generatedTrack);
  }
  // Module 8 BAKE: transition gestures written directly as Notes on percussion +
  // melody tracks. Bypasses the semantic pipeline by design (fixed performance
  // semantics; Module 12 generalizes percussion). Deterministic, no RNG.
  const gestured = applyArrangementGestures(returned, { project, measures: arrangementInfo.measures, config: arrangement });
  // Final truncation pass: the articulation duration multiplier can push a note a
  // few ticks past a breakdown boundary after the event-level drop; the spec's
  // "instant mute" is note-level, so enforce it on the built tracks.
  const truncated = truncateNotesAtBreakdownBoundaries(gestured, arrangementInfo.windows);
  // Module 8.5 §5 — chorus role divider: post-bake, after gestures, BEFORE the
  // guard (the guard stays the FINAL invariant below). Deterministic; expected
  // ≈ 0 resolutions; doubling guests are exempt (they follow their source).
  const divided = rotationPlan ? divideChorusRoles(truncated, rotationPlan) : truncated;
  // Polyphony hotfix Phase 4 — MonophonyGuard is the FINAL invariant: it runs LAST
  // (after humanization, breakdown truncation and any Module 8 gestures) so that
  // timing shifts from those stages can never re-stack a monophonic track.
  // Deterministic: truncation to a legato handoff, drops only for tied onsets;
  // pitch is never modified. Expected resolutions after Phases 1–3: zero.
  return divided.map((track) => {
    if (track.family === "structure" || track.family === "audio") return track;
    const guarded = guardTrackNotes(track.id, track.role, track.notes);
    return { ...track, notes: guarded.notes };
  });
}
function humanizeNotes(notes: Note[], bpm: number, seed: number, intensity: number, rubato: number): Note[] {
  const rng = mulberry32(seed);
  const maxOffset = Math.max(0, Math.floor((14.5 / 60000) * bpm * PPQ * intensity));
  return notes.map((note) => {
    const offset = Math.round(rng() * maxOffset);
    const elastic = Math.round(Math.sin(note.startTick / PPQ) * (rubato / 100) * (PPQ / 8));
    const drift = Math.max(-Math.floor((PPQ * rubato) / 200), Math.min(Math.floor((PPQ * rubato) / 200), Math.round((rng() * 2 - 1) * (PPQ * rubato / 200))));
    return { ...note, startTick: Math.max(0, note.startTick + offset + elastic + drift), durationTicks: Math.max(1, note.durationTicks - offset),
      velocity: clamp(note.velocity + Math.round((rng() * 2 - 1) * 12 * intensity), 1, 127) };
  }).sort((a, b) => a.startTick - b.startTick || a.pitch - b.pitch);
}

export function fillRandomNotes(project: Project, count: number, seed = 42): Track[] {
  const rng = mulberry32(seed), end = projectEndTick(project);
  const tracks = project.tracks.filter((track) => track.family !== "structure" && track.family !== "audio");
  const notes = new Map(tracks.map((track) => [track.id, [] as Note[]]));
  for (let index = 0; index < count && tracks.length; index++) {
    const track = tracks[Math.floor(rng() * tracks.length)];
    notes.get(track.id)!.push({ pitch: Math.floor(track.lowestNote + rng() * (track.highestNote - track.lowestNote + 1)),
      startTick: Math.floor(rng() * Math.max(1, end - 120)), durationTicks: Math.max(1, Math.min(1920, end)), velocity: 40 + Math.floor(rng() * 81) });
  }
  return project.tracks.map((track) => ({ ...track, notes: notes.get(track.id) ?? track.notes.map((note) => ({ ...note })) }));
}
export function midiName(note: number): string { return `${PITCH_CLASS_NAMES[pc(note)]}${Math.floor(note / 12) - 1}`; }
export function generationSummary(project: Project): string {
  const end = projectEndTick(project), barTicks = ticksPerBar(project.timeSignature), bars = Math.round(end / barTicks);
  const lines = [`=== Semantic orchestration harness ===`, `Project: ${project.name}  BPM ${project.bpm}  ${project.timeSignature.numerator}/${project.timeSignature.denominator}  key=${project.key} mode=${project.mode}`, `End: ${bars} bars (${end} ticks)`, ""];
  for (const track of project.tracks) if (track.family !== "structure" && track.family !== "audio") lines.push(`${track.name.padEnd(18)} ${String(track.notes.length).padStart(5)} notes`);
  return lines.join("\n");
}
