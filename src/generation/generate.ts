export type LowIntervalZone = "SUB_BASS" | "MID_BASS" | "TENOR_ALTO" | "TREBLE";
/** Overtone-zone boundaries: C1=24 (C1), C2=36, C3=48, C4=60. Below C3 is the
 * mud-prone region where the interval matrix below applies; C3–C4 allows 3rds/m7s
 * and tritones; C4+ is unconstrained by zone rules. */
export function zoneOf(pitch: number): LowIntervalZone {
  if (pitch < 36) return "SUB_BASS";   // C1–C2: octaves only
  if (pitch < 48) return "MID_BASS";   // C2–C3: P4/P5/octaves only
  if (pitch < 60) return "TENOR_ALTO"; // C3–C4: 3rds, m7, tritones OK
  return "TREBLE";
}

/** Zone interval compliance for adjacent voices BOTH below C3 (MIDI 48);
 * straddling pairs (lower < 48, upper ≥ 48) stay governed by the spacing-
 * minimum rules in OvertoneSpacingFilter, which are already sufficient. */
export function isZoneCompliantInterval(lower: number, upper: number): boolean {
  if (lower >= 48) return true;
  const intervalPc = (((upper - lower) % 12) + 12) % 12;
  if (lower < 36 && upper < 36) return intervalPc === 0;                     // sub-bass: octaves only
  return intervalPc === 0 || intervalPc === 5 || intervalPc === 7;           // mid-bass: P4/P5/8ve
}
